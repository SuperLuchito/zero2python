/** Short explanations supplement Python's original error, without guessing a fix. */
export function explainPythonError(name:string):string {
  const messages:Record<string,string> = {
    SyntaxError:'Python не смог разобрать запись. Проверьте двоеточия, скобки, кавычки и порядок символов в указанной строке.',
    IndentationError:'Проверьте отступы: строки одного блока должны начинаться на одном уровне.',
    TabError:'В отступах смешаны табуляции и пробелы. Используйте четыре пробела на уровень.',
    NameError:'Использовано имя, которому ещё не присвоено значение. Проверьте написание и порядок строк.',
    TypeError:'Операция получила неподходящий тип или неверное число аргументов. Сверьте их с условием.',
    ValueError:'Тип аргумента допустим, но его значение не подходит для этой операции.',
    ZeroDivisionError:'Знаменатель оказался равен нулю. Проверьте этот случай до деления.',
    IndexError:'Индекс выходит за границы последовательности. Первый индекс — 0, последний — len(...) − 1.',
    KeyError:'В словаре нет запрошенного ключа. Проверьте, должен ли он присутствовать по условию.',
    AssertionError:'Одна из проверок не прошла. Сверьте результат, типы и граничные случаи с условием и примерами.',
  };
  return messages[name] ?? 'Выполнение остановилось из-за исключения. Ниже сохранено исходное сообщение Python.';
}
